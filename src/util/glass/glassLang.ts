export type GlassLangKey = keyof typeof EN;

export function getGlassStrings(langCode?: string) {
  return langCode?.toLowerCase().startsWith('ru') ? RU : EN;
}

export default function useGlassLang() {
  const lang = useLang();
  const strings = getGlassStrings(lang.rawCode || navigator.language);

  return (key: GlassLangKey) => strings[key];
}
